NativeDirection nativeDirectionVector(int64_t deltaX,int64_t deltaY) {
    const auto x=std::abs(deltaX),y=std::abs(deltaY);
    const bool swapped=x>y;
    const auto major=std::max(x,y),minor=std::min(x,y);
    const auto tangent=major?size_t(127*minor/major):0;
    const auto &entry=directions.at(tangent);
    auto angle=int(entry.angle);
    int32_t directionX=entry.minor,directionY=entry.major;
    if(swapped) {std::swap(directionX,directionY);angle=(-1-angle)&0xF;}
    if(deltaY<0) {directionY=-directionY;angle=(-1-angle)&0x1F;}
    if(deltaX>=0) angle=(-1-angle)&0x3F;
    else directionX=-directionX;
    return {directionX,directionY,uint8_t((angle+8)&0x3F)};
}
