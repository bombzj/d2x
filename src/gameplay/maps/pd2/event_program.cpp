void shuffleMapEvent(std::span<int> values,uint32_t seed) {
    // 41d49 361500 seeds MT19937. 361780 performs forward Fisher-Yates;
    // 3617F0 uses this rejection/modulo rule, not a platform's std::shuffle
    // or uniform_int_distribution. The engine is freshly seeded each call.
    std::mt19937 random(seed);
    for(size_t index=1;index<values.size();++index) {
        const auto bound=uint32_t(index+1);uint32_t value;
        do value=uint32_t(random());
        while(UINT32_MAX/bound<=value/bound && UINT32_MAX%bound!=bound-1);
        const auto selected=size_t(value%bound);
        if(selected!=index) std::swap(values[index],values[selected]);
    }
}
