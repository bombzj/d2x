int selectMapController(int level,int quality,bool force,uint32_t &random) {
    if(const int fixed=fixedMapController(level)) return fixed;
    if(excludesRandomEvent(level)) return 10;
    const auto chance=pd2CrtRandom(random)%100;
    const auto threshold=quality==2?11u:quality==4?17u:34u;
    if(force || chance<threshold) {
        int program{};
        for(int attempt=0;attempt<40;++attempt) {
            switch(pd2CrtRandom(random)%12) {
            case 1:return 11;
            case 2:return 12;
            case 3:case 7:program=0;break;
            case 4:return 14;
            case 5:return 15;
            case 6:return 16;
            case 8:return 18;
            case 9:if(!force) return 19;program=0;break;
            case 10:return 20;
            case 11:return 21;
            default:program=force?0:10;break;
            }
        }
        return program?program:10;
    }
    return 10;
}
